// Shared pieces for the CUDA and SYCL device benchmarks: the benchmarked
// operations, the compute-bound chain recurrences, host-side input generation,
// and result-table printing. The backend files own memory management, kernel
// launch, and timing.
//
// Every benchmark compares the safe type against its own basis type running
// the identical kernel, so the ratio isolates the cost of the safety checks.
// Input ranges are chosen so that no check ever fires, even for the 8-bit
// types; the error path is never part of a timed region.

