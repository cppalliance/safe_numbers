// Verification and reporting
// ---------------------------------------------------------------------------

template <typename TB, typename TS>
long long count_mismatches(const std::vector<TB>& builtin_out, const std::vector<TS>& safe_out)
{
    long long bad {0};
    for (std::size_t i {0}; i < builtin_out.size(); ++i)
    {
        if (builtin_out[i] != as_builtin<TB>(safe_out[i]))
        {
            ++bad;
        }
    }
    return bad;
}

inline void print_table_header(const char* type_name, const char* shape)
{
    std::printf("\n=== %s : %s ===\n", type_name, shape);
    std::printf("%-8s %16s %16s %8s   %s\n", "op", "builtin (ns/op)", "safe (ns/op)", "ratio", "verify");
}

// Returns 1 if verification failed so callers can accumulate a failure count
inline int print_row(const char* op, const double builtin_ns, const double safe_ns, const long long mismatches)
{
    const auto ratio {builtin_ns > 0.0 ? safe_ns / builtin_ns : 0.0};
    if (mismatches == 0)
    {
        std::printf("%-8s %16.4f %16.4f %8.2f   ok\n", op, builtin_ns, safe_ns, ratio);
        return 0;
    }

    std::printf("%-8s %16.4f %16.4f %8.2f   FAIL (%lld mismatches)\n", op, builtin_ns, safe_ns, ratio, mismatches);
    return 1;
}

