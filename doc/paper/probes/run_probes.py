# Drive the semantic probes across the compared libraries. For every
# (library, probe) pair the probe file is compiled with -DPROBE=n; a failed
# compile is recorded as a compile-time rejection (with the first diagnostic),
# otherwise the binary runs and its single output line is recorded.
#
# Usage:
#   python3 run_probes.py --boost-root DIR --intel DIR --safeint DIR [--cxx clang++] [--latex]
#
# The probes, in order:
#   1 narrow overflow (u8 255 + 1)
#   2 unsigned underflow (u32 0 - 1)
#   3 overflow at the declared width (u32 2^31 * 2)
#   4 signed asymmetric case (INT_MIN / -1)
#   5 division by a runtime zero
#   6 mixed signedness comparison (-1 < 1u)
#   7 truncating conversion (u32 300 -> u8)
#   8 mixed width arithmetic (u8 + u32)
#   9 construction from bool
#  10 bounded domain [0, 100]: 60 + 50

import argparse
import os
import subprocess
import sys
import tempfile

PROBES = [
    (1, "u8 255 + 1"),
    (2, "u32 0 - 1"),
    (3, "u32 2^31 * 2"),
    (4, "i32 INT_MIN / -1"),
    (5, "u32 x / 0 (runtime)"),
    (6, "i32(-1) < u32(1)"),
    (7, "u32 300 -> u8"),
    (8, "u8 + u32"),
    (9, "construct from bool"),
    (10, "[0,100]: 60 + 50"),
]

BOOST_LIBS_SN = ["safe_numbers", "int128", "assert", "config", "throw_exception", "core", "static_assert"]
BOOST_LIBS_SNX = ["safe_numerics", "config", "mp11", "integer", "core", "logic", "concept_check",
                  "type_traits", "static_assert", "assert", "throw_exception", "preprocessor",
                  "utility", "move"]


def include_flags(boost_root, libs):
    flags = []
    for lib in libs:
        flags += ["-I", os.path.join(boost_root, "libs", lib, "include")]
    return flags


def run_one(cxx, source, flags, probe, workdir):
    exe = os.path.join(workdir, "probe_{}".format(probe))
    cmd = [cxx, "-std=c++20", "-O1", "-DPROBE={}".format(probe), *flags, source, "-o", exe]
    comp = subprocess.run(cmd, capture_output=True, text=True)
    if comp.returncode != 0 or not os.path.exists(exe):
        first = ""
        for line in comp.stderr.splitlines():
            if "error:" in line:
                first = line.split("error:", 1)[1].strip()
                break
        return ("COMPILE_ERROR", first[:110])
    run = subprocess.run([exe], capture_output=True, text=True, timeout=60)
    out = (run.stdout.strip().splitlines() or [""])[0]
    if run.returncode != 0 and not out:
        return ("CRASH", "exit {}".format(run.returncode))
    return ("RAN", out)


def adoc_cell(status, detail):
    # Condense a raw outcome into a short table cell
    if status == "COMPILE_ERROR":
        return "compile-time error"
    if status == "CRASH":
        return "crashed ({})".format(detail)
    if detail.startswith("THREW "):
        what = detail[len("THREW "):].split(": ", 1)[0]
        what = what.replace("boost::wrapexcept<", "").rstrip(">").replace("std::__1::", "std::")
        what = what.split(" ")[0]
        return "throws `{}`".format(what)
    if detail.startswith("VALUE "):
        return "value `{}`, no error".format(detail[len("VALUE "):])
    if detail.startswith("NOT_EXPRESSIBLE"):
        return "not expressible"
    return detail


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--boost-root", required=True)
    parser.add_argument("--intel", required=True, help="checkout of intel/safe-arithmetic")
    parser.add_argument("--safeint", required=True, help="checkout of dcleblanc/SafeInt")
    parser.add_argument("--cxx", default="clang++")
    parser.add_argument("--latex", action="store_true")
    parser.add_argument("--adoc", action="store_true", help="emit an AsciiDoc table for the manual")
    args = parser.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    libraries = [
        ("Boost.SafeNumbers", os.path.join(here, "probe_safe_numbers.cpp"),
         include_flags(args.boost_root, BOOST_LIBS_SN)),
        ("Boost.SafeNumerics", os.path.join(here, "probe_safe_numerics.cpp"),
         include_flags(args.boost_root, BOOST_LIBS_SNX)),
        ("Intel safe-arithmetic", os.path.join(here, "probe_intel.cpp"),
         ["-I", os.path.join(args.intel, "include"), *include_flags(args.boost_root, ["mp11"])]),
        ("Microsoft SafeInt", os.path.join(here, "probe_safeint.cpp"),
         ["-I", args.safeint]),
    ]

    results = {}
    with tempfile.TemporaryDirectory() as workdir:
        for name, source, flags in libraries:
            for probe, _ in PROBES:
                results[(name, probe)] = run_one(args.cxx, source, flags, probe, workdir)

    if args.adoc:
        print("// Generated by doc/paper/probes/run_probes.py --adoc. Do not edit by hand.")
        print('[cols="3,2,2,2,2",options="header"]')
        print("|===")
        print("| Probe | " + " | ".join(name for name, _, _ in libraries))
        for probe, label in PROBES:
            cells = [adoc_cell(*results[(name, probe)]) for name, _, _ in libraries]
            print("| P{} `{}` | {}".format(probe, label, " | ".join(cells)))
        print("|===")
        return

    if args.latex:
        for probe, label in PROBES:
            cells = []
            for name, _, _ in libraries:
                status, detail = results[(name, probe)]
                cells.append("CT" if status == "COMPILE_ERROR" else detail)
            print("{} & {} \\\\".format(label, " & ".join(cells)))
        return

    for name, _, _ in libraries:
        print("== {}".format(name))
        for probe, label in PROBES:
            status, detail = results[(name, probe)]
            print("  P{:<2d} {:24s} {:14s} {}".format(probe, label, status, detail))
        print()


if __name__ == "__main__":
    main()
